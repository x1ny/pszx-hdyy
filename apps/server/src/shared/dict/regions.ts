const countryByCode = new Map(COUNTRY_REGIONS.map((item) => [item.code, item]));
const provinceByCode = new Map(PROVINCES.map((item) => [item.code, item]));
const cityByCode = new Map(CITIES.map((item) => [item.code, item]));

export const findCountryRegion = (code: string | null | undefined) =>
  code ? (countryByCode.get(code) ?? null) : null;

export const findProvince = (code: string | null | undefined) =>
  code ? (provinceByCode.get(code) ?? null) : null;

export const findCity = (code: string | null | undefined) =>
  code ? (cityByCode.get(code) ?? null) : null;

/** 某个省下的地级行政区。直辖市和港澳台返回空数组——它们本来就没有市级。 */
export const citiesOfProvince = (provinceCode: string | null | undefined) =>
  provinceCode
    ? CITIES.filter((city) => city.provinceCode === provinceCode)
    : [];
