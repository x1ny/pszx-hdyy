/**
 * 国别/地区 + 中国省市字典。
 *
 * **这个文件必须保持零 import。** 它是 `@repo/server` 唯一允许被 `apps/web`
 * runtime import 的东西（package.json 的 "./dict" 导出），前提就是它不会顺着
 * import 链把 pg 之类的服务端依赖拽进浏览器包——加一行 import 就破了这个前提。
 *
 * 数据来源与生成日期（2026-08-25）：
 * - 国家/地区：CLDR zh_CN 译名，https://raw.githubusercontent.com/umpirsky/country-list/master/data/zh_CN/country.json
 * - 省市：国家统计局行政区划，https://raw.githubusercontent.com/modood/Administrative-divisions-of-China/master/dist/{provinces,cities}.json
 *
 * 抓下来之后做了四处加工，更新数据时照做：
 * 1. 国家列表**剔除 HK / MO / TW**。港澳台不是"国别"，它们在下面的省级列表里
 *    （GB/T 2260 的 71 / 81 / 82）。所以联动判断就是一句 `code === "CN"`。
 * 2. 国家中文名只改两条：SZ 斯威士兰 → 埃斯瓦蒂尼（2018 年正式改名）、
 *    PS 巴勒斯坦领土 → 巴勒斯坦国（我方表述）。其余照 CLDR 原样，每多改一条就
 *    多一处以后没人说得清为什么和标准不一样的地方。
 * 3. 省级列表**手工补上 71 台湾省 / 81 香港特别行政区 / 82 澳门特别行政区**——
 *    统计局那份数据里没有这三条。
 * 4. 市级列表剔除"市辖区""县""省直辖县级行政区划""自治区直辖县级行政区划"这类
 *    占位项。结果是**直辖市和港澳台没有市级**，籍贯选到省即止（省必选、市选填）。
 *
 * 码是权威，名字只用于显示。库里两者都存，但名字是写入时的快照，
 * 任何查询/筛选/去重都走码。
 */

